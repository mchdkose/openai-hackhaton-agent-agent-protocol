import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';

const origin = process.env.SMOKE_ORIGIN || 'http://localhost:3000';
const question = "My mother's birthday is tonight. Send at least 25 red roses to Kadikoy by 20:00, under 1,500 TRY including delivery.";
const tenantIds = ['rose-and-stem', 'petal-atelier', 'tulip-house'];
const expected = ['yes', 'no', 'partial'];
const results = [];
const timings = [];
async function get(path) {
  const started = performance.now();
  const response = await fetch(new URL(path, origin), { signal: AbortSignal.timeout(50_000) });
  timings.push({path:new URL(path, origin).pathname,ms:Math.round(performance.now()-started)});
  assert.equal(response.status, 200, `GET ${new URL(path, origin).pathname}`);
  assert.match(response.headers.get('cache-control') || '', /no-store/);
  assert.equal(response.headers.get('referrer-policy'), 'no-referrer');
  const body = await response.json();
  if(body.requirements) assert.equal(body.requirements.language, 'en');
  for(const link of body.next || []) assert.equal(new URL(link.url).origin, new URL(origin).origin, `Link origin for ${link.rel}`);
  return body;
}
const discovery = await get('/askagent?format=json');
assert.equal(discovery.merchants.length, 3);
for(const merchant of discovery.merchants) for(const url of [merchant.conversation,merchant.storefront]) assert.equal(new URL(url).origin, new URL(origin).origin);
const responses = await Promise.all(tenantIds.map(async (id, index) => {
  const response = await get(`/t/${id}/askagent?ask=${encodeURIComponent(question)}&format=json`);
  assert.equal(response.status, expected[index], id);
  assert(/^h_[a-f0-9]{32}$/.test(response.h), 'Conversation handle format');
  assert(response.next.every(link => link.url.startsWith('http')));
  results.push({ tenant: id, status: response.status, mode: response.mode, check: response.referee?.verdict });
  return response;
}));
assert.equal(new Set(responses.map(response => response.h)).size, 3);
const winner = responses[0];
const item = winner.matches.find(item => item.eligible);
assert.equal(item.total, 1370);
const continued = await get(`/t/rose-and-stem/askagent?ask=${encodeURIComponent('Card message: Happy birthday, Mom.')}&h=${winner.h}&format=json`);
assert(continued.h === winner.h, 'Conversation handle continuity');
assert(continued.requirements.note === 'Happy birthday, Mom.', 'Card message continuity');
assert.equal(continued.requirements.budget, 1500);
const quote = await get(`/t/rose-and-stem/askagent/quote?h=${winner.h}&sku=${item.sku}&zone=kadikoy&format=json`);
assert.equal(quote.quote.total, 1370);
assert.equal(quote.quote.same_price_for_everyone, true);
const transcript = await get(`/t/rose-and-stem/askagent/transcript?h=${winner.h}&format=json`);
assert.equal(transcript.transcript.length, 2);
assert(transcript.requirements.note === 'Happy birthday, Mom.', 'Transcript card message continuity');
const checkout = await get(`/t/rose-and-stem/askagent/checkout?h=${winner.h}&sku=${item.sku}&format=json`);
const handoff = checkout.next.find(link => link.rel === 'checkout');
assert(handoff.url.includes(`/p/${item.sku}`));
const product = await fetch(new URL(`/t/rose-and-stem/p/${item.sku}?h=${winner.h}`, origin));
assert.equal(product.status, 200);
assert.equal(product.headers.get('referrer-policy'), 'no-referrer');
const html = await product.text();
assert(html.includes('Happy birthday, Mom.'));
const before = await get('/api/panel');
const orderBody = JSON.stringify({ tenant: 'rose-and-stem', h: winner.h, sku: item.sku });
const postOrder = async () => {
  const response = await fetch(new URL('/api/order', origin), { method: 'POST', headers: {'Content-Type':'application/json',Origin:origin}, body: orderBody });
  assert.equal(response.status, 200);
  return response.json();
};
const first = await postOrder();
const again = await postOrder();
assert.equal(first.orderId, again.orderId);
assert.equal(first.demo, true);
const after = await get('/api/panel');
assert.equal(after.orders, before.orders + 1);
const history = JSON.stringify(after);
assert(!history.includes(winner.h));
assert(!history.includes('Happy birthday, Mom.'));
assert(!history.includes('OPENROUTER_API_KEY'));
const checks = ['three independent source-backed outcomes', 'delivery-inclusive price', 'tenant-isolated handles', 'English conversation continuity', 'card message', 'deterministic quote', 'transcript handoff', 'server-rendered merchant handoff', 'explicit POST order', 'order idempotency', 'private audit log'];
await mkdir('artifacts', {recursive:true});
await writeFile('artifacts/smoke-result.json', JSON.stringify({at:new Date().toISOString(), origin, checks, responses:results, timings, success:true},null,2)+'\n');
console.log(JSON.stringify({success:true,origin,checks:checks.length,outcomes:results.map(result=>({tenant:result.tenant,status:result.status,mode:result.mode})),order:'simulated and idempotent',timings},null,2));
